// ─────────────────────────────────────────────────────────────────────────────
// Seed — demo media assets
// Blueprint 05: every asset carries an ownership label and a moderation state.
// Blueprint 07: an image without alt text is not accessible, so every row here
// has one.
//
// The seed writes real bytes. A `MediaAsset` row whose file is missing would
// render as a broken image in the demo, so each row below is backed by an SVG or
// text file generated on the spot and written through the configured storage
// root. Only formats we can synthesize are seeded — no fabricated audio or video
// assets, because shipping binaries in a seed is worse than not having them.
// ─────────────────────────────────────────────────────────────────────────────

